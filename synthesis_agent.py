"""
Step 6d: Synthesis agent -- Groq version.

Takes the Planner's plan, Correlation's assessment, Evidence's citations,
and the Critic's verdict, and writes an actual clinician-facing report in
plain English (markdown). This is the final piece of the architecture --
everything before this produced structured JSON for internal use; this
produces the thing a human actually reads.

Design decision: if the Critic returned verdict "needs_revision", this
agent still writes a report (so the pipeline stays testable end-to-end),
but is explicitly instructed to include a prominent, impossible-to-miss
CAVEATS section listing every issue the Critic found, rather than silently
producing a clean-looking report over a flawed pipeline run.

Setup:
    pip install groq python-dotenv

Add to your .env:
    GROQ_API_KEY=gsk_...
    SYNTHESIS_MODEL=openai/gpt-oss-120b
"""

import json
import os
from datetime import datetime

from dotenv import load_dotenv
from groq import Groq

from llm_utils import normalize_verdict, strip_code_fences

load_dotenv()

_client = None


def _get_client() -> Groq:
    global _client
    if _client is None:
        _client = Groq(api_key=os.getenv("GROQ_API_KEY"), max_retries=5)
    return _client


SYNTHESIS_SYSTEM_PROMPT = """You are a synthesis agent writing an AI-assisted \
radiology decision-support report, formatted like a real clinical radiology \
report, for a licensed clinician to review. You do NOT diagnose and you \
MUST NOT state or imply a definitive diagnosis. Every claim must be \
traceable to the CV findings, the planner's reasoning, the correlation \
assessment, or the retrieved evidence provided to you -- do not introduce \
new clinical claims of your own.

Note on evidence: each evidence item has "queried_for" (the finding it was
retrieved for) and "matched_pathology" (what the closest available
reference actually discusses -- these can differ if no exact match
exists). Match evidence to findings using "queried_for". If
"matched_pathology" differs from "queried_for", say so explicitly (e.g.
"closest available reference discusses Nodule, not an exact match for
Mass") rather than treating it as no evidence at all.

Write the report in markdown, in this exact structure:

**RADIOLOGY COPILOT -- AI-ASSISTED DECISION SUPPORT REPORT**

A header table with these rows: Study ID | Filename | Date Generated |
Pipeline Status (pass/needs_revision, from the critic verdict).

## FINDINGS
For each priority finding: its probability, one line of plain description
drawing on the retrieved evidence (cite the source), and note explicitly
if the evidence was an imperfect match.

## IMPRESSION
2-4 concise sentences summarizing the overall picture, in the terse,
declarative style of a real radiology report -- state what was observed,
not a diagnosis.

## SYMPTOM CORRELATION
One or two sentences on whether patient-reported symptoms support the
findings, or a note that correlation was skipped and why.

## CAVEATS AND LIMITATIONS
If the critic's verdict was "needs_revision", list EVERY issue found here,
verbatim, under a bolded "**Pipeline flagged issues -- review before \
relying on this report:**" heading. This is NOT optional if issues exist. \
If verdict was "pass", state only the general AI-assistance limitation.

## ADVICE
Always include: "Please correlate clinically. This output requires review \
and sign-off by a licensed radiologist or clinician before any action is \
taken."

---
*Generated by an AI pipeline (Planner, Correlation, Evidence/RAG, Critic, \
Synthesis agents) -- not a licensed radiologist. This report is AI-generated \
decision support, not a diagnosis, and has no medico-legal validity.*
"""


def generate_report(study_id: int, study_filename: str, plan: dict, correlation: dict, evidence: list, critique: dict) -> dict:
    """
    Returns {"report_text": str, "status": "pass" | "needs_revision" | "error"}
    """
    if critique is None or "error" in (critique or {}):
        return {
            "report_text": None,
            "status": "error",
            "error": "Cannot synthesize a report: an earlier pipeline stage failed or the critic did not run.",
        }

    client = _get_client()
    model = os.getenv("SYNTHESIS_MODEL", "openai/gpt-oss-120b")

    generated_at = datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")

    user_message = (
        f"Study ID: {study_id}\n"
        f"Study filename: {study_filename}\n"
        f"Date generated: {generated_at}\n\n"
        f"PLANNER OUTPUT:\n{json.dumps(plan, indent=2)}\n\n"
        f"CORRELATION OUTPUT:\n{json.dumps(correlation, indent=2)}\n\n"
        f"EVIDENCE RETRIEVED:\n{json.dumps(evidence, indent=2)}\n\n"
        f"CRITIC VERDICT:\n{json.dumps(critique, indent=2)}\n"
    )

    try:
        response = client.chat.completions.create(
            model=model,
            messages=[
                {"role": "system", "content": SYNTHESIS_SYSTEM_PROMPT},
                {"role": "user", "content": user_message},
            ],
            max_tokens=1500,
        )
    except Exception as e:
        # Same error shape as above, so the API and UI can show a readable
        # message instead of a raw HTTP 500 (e.g. on a Groq rate limit).
        return {
            "report_text": None,
            "status": "error",
            "error": f"Report generation failed while calling Groq (model={model}): {e}",
        }

    report_text = strip_code_fences(response.choices[0].message.content or "")

    # Fail safe: anything that is not an explicit "pass" means the critic
    # flagged something, so the UI must show its caveat banner. Previously
    # an unrecognised verdict produced a caveat-free "clean" report.
    status = normalize_verdict(critique)

    return {"report_text": report_text, "status": status}


if __name__ == "__main__":
    from database import list_studies, get_study
    from planner_agent_groq import plan_next_steps
    from correlation_agent_groq import correlate_findings
    from evidence_agent import retrieve_evidence
    from critic_agent import critique_pipeline

    studies = list_studies()
    if not studies:
        print("No studies found. Upload an X-ray through /analyze-xray first.")
    else:
        latest = studies[0]
        study = get_study(latest["id"])
        findings = {f["pathology"]: f["probability"] for f in study["findings"]}
        symptoms = "Cough, fever, and shortness of breath for 3 days."

        print(f"Running full pipeline + synthesis on study {latest['id']} ({study['filename']})...\n")

        plan = plan_next_steps(findings, patient_symptoms=symptoms)
        if "error" in plan:
            print("Planner failed -- stopping.")
        else:
            priority = {item["pathology"]: item["probability"] for item in plan.get("priority_findings", [])}

            if plan.get("requires_correlation_with_symptoms"):
                correlation = correlate_findings(priority, patient_symptoms=symptoms)
            else:
                correlation = {"skipped": "Planner determined correlation was not required."}

            evidence = []
            for pathology in priority:
                evidence.extend(retrieve_evidence(pathology, top_k=1))

            critique = critique_pipeline(plan, correlation, evidence)

            report = generate_report(latest["id"], study["filename"], plan, correlation, evidence, critique)
            print(f"STATUS: {report['status']}\n")
            print(report["report_text"] or report.get("error"))